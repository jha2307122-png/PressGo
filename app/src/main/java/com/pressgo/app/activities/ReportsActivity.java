package com.pressgo.app.activities;

import android.content.Intent;
import android.os.Bundle;
import android.util.Log;
import android.view.View;
import android.widget.Toast;

import androidx.appcompat.app.AppCompatActivity;

import com.pressgo.app.databinding.ActivityReportsBinding;
import com.pressgo.app.models.PrintOrder;
import com.pressgo.app.repositories.OrderRepository;
import com.pressgo.app.utils.SessionManager;

import java.util.List;
import java.util.Locale;

public class ReportsActivity extends AppCompatActivity {
    private static final String TAG = "ReportsActivity";

    private ActivityReportsBinding binding;
    private String shopId;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        Log.d(TAG, "onCreate");
        binding = ActivityReportsBinding.inflate(getLayoutInflater());
        setContentView(binding.getRoot());

        shopId = getIntent().getStringExtra("shopId");
        if (shopId == null || shopId.isEmpty()) {
            shopId = new SessionManager(this).getShopId();
        }
        if (shopId == null || shopId.isEmpty()) {
            shopId = "shop_campus_main";
        }

        setSupportActionBar(binding.toolbar);
        if (getSupportActionBar() != null) {
            getSupportActionBar().setDisplayHomeAsUpEnabled(true);
            getSupportActionBar().setTitle("Analytics & Operational Reports");
        }
        binding.toolbar.setNavigationOnClickListener(v -> finish());

        setupListeners();
        loadAnalytics();
    }

    private void setupListeners() {
        binding.chipToday.setOnClickListener(v -> loadAnalytics());
        binding.chipThisWeek.setOnClickListener(v -> loadAnalytics());
        binding.chipThisMonth.setOnClickListener(v -> loadAnalytics());

        binding.btnExportReport.setOnClickListener(v -> exportReport());
    }

    private void loadAnalytics() {
        binding.progressBar.setVisibility(View.VISIBLE);
        OrderRepository.getInstance().getShopOrders(shopId, orders -> {
            binding.progressBar.setVisibility(View.GONE);
            calculateMetrics(orders);
        }, e -> {
            binding.progressBar.setVisibility(View.GONE);
            Log.e(TAG, "Error loading orders for report", e);
        });
    }

    private void calculateMetrics(List<PrintOrder> orders) {
        int total = orders.size();
        int completed = 0;
        int cancelled = 0;
        int pending = 0;
        double revenue = 0.0;
        int colorJobs = 0;
        int bwJobs = 0;

        for (PrintOrder o : orders) {
            if (PrintOrder.STATUS_COMPLETED.equals(o.getOrderStatus())) {
                completed++;
                revenue += o.getEstimatedPrice();
            } else if (PrintOrder.STATUS_CANCELLED.equals(o.getOrderStatus()) || PrintOrder.STATUS_REJECTED.equals(o.getOrderStatus())) {
                cancelled++;
            } else {
                pending++;
            }

            if (o.isColor()) {
                colorJobs++;
            } else {
                bwJobs++;
            }
        }

        binding.tvTotalOrdersVal.setText(String.valueOf(total));
        binding.tvCompletedOrdersVal.setText(String.valueOf(completed));
        binding.tvCancelledOrdersVal.setText(String.valueOf(cancelled));
        binding.tvRevenueVal.setText(String.format(Locale.US, "BDT %.2f", revenue));

        double cancelRate = total > 0 ? ((double) cancelled / total) * 100 : 0;
        binding.tvCancellationRateVal.setText(String.format(Locale.US, "%.1f%%", cancelRate));

        binding.tvColorRatioVal.setText(String.format(Locale.US, "Color: %d | B&W: %d", colorJobs, bwJobs));
        binding.tvAvgTurnaroundVal.setText("~14 mins");
    }

    private void exportReport() {
        StringBuilder sb = new StringBuilder();
        sb.append("================================\n");
        sb.append("   PRESSGO OPERATIONAL REPORT   \n");
        sb.append("================================\n\n");
        sb.append("Shop ID:           ").append(shopId).append("\n");
        sb.append("Total Orders:      ").append(binding.tvTotalOrdersVal.getText()).append("\n");
        sb.append("Completed Orders:  ").append(binding.tvCompletedOrdersVal.getText()).append("\n");
        sb.append("Cancelled Orders:  ").append(binding.tvCancelledOrdersVal.getText()).append("\n");
        sb.append("Verified Revenue:  ").append(binding.tvRevenueVal.getText()).append("\n");
        sb.append("Cancellation Rate: ").append(binding.tvCancellationRateVal.getText()).append("\n");
        sb.append("Turnaround Time:   ").append(binding.tvAvgTurnaroundVal.getText()).append("\n\n");
        sb.append("Generated by PressGo Admin Portal\n");

        Intent sendIntent = new Intent(Intent.ACTION_SEND);
        sendIntent.setType("text/plain");
        sendIntent.putExtra(Intent.EXTRA_SUBJECT, "PressGo Operational Report");
        sendIntent.putExtra(Intent.EXTRA_TEXT, sb.toString());
        startActivity(Intent.createChooser(sendIntent, "Export Report via"));
    }

    @Override
    protected void onDestroy() {
        super.onDestroy();
        Log.d(TAG, "onDestroy");
    }
}
